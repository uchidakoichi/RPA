#Requires -Version 5.1
<#
.SYNOPSIS
    Builds ps\fujikyun.ps1, the one script file of the app, from ps\build\Main.ps1, ps\src and ps\gui.

.DESCRIPTION
    Maintainers only. Run it after changing a file in src, gui or Main.ps1:
        powershell -NoProfile -File ps\build\Build-FujiBundle.ps1
        pwsh -NoProfile -File ps/build/Build-FujiBundle.ps1
    -PassThru returns the text instead of writing the file (the tests check that fujikyun.ps1 is
    up to date with it).
#>
[CmdletBinding()]
param([switch]$PassThru)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$psRoot = Split-Path -Path $PSScriptRoot -Parent
$mark = '# @@SOURCES@@'
$main = [System.IO.File]::ReadAllText((Join-Path $PSScriptRoot 'Main.ps1'))
if (([regex]::Matches($main, [regex]::Escape($mark))).Count -ne 1) { throw ('Main.ps1 must contain the mark "{0}" once' -f $mark) }

$parts = New-Object -TypeName 'System.Collections.Generic.List[string]'
foreach ($folder in @('src', 'gui')) {
    # Ordinal order, the same on every PowerShell version and culture
    $files = @(Get-ChildItem -LiteralPath (Join-Path $psRoot $folder) -Filter '*.ps1' | ForEach-Object { $_.Name })
    [Array]::Sort($files, [System.StringComparer]::Ordinal)
    foreach ($name in $files) {
        $text = [System.IO.File]::ReadAllText((Join-Path (Join-Path $psRoot $folder) $name))
        $parts.Add(('# ===== {0}/{1} =====' -f $folder, $name) + "`n" + $text.Trim() + "`n")
    }
}
$note = '# Built by ps/build/Build-FujiBundle.ps1 from ps/build/Main.ps1, ps/src/*.ps1 and ps/gui/*.ps1.' + "`n" +
    '# Do not edit this file: edit those and build again.' + "`n"
$text = $note + $main.Replace($mark, ($parts -join "`n"))
$text = ($text -replace "`r`n", "`n") -replace "`n", "`r`n"
if ($PassThru) { return $text }
$out = Join-Path $psRoot 'fujikyun.ps1'
[System.IO.File]::WriteAllText($out, $text, (New-Object -TypeName System.Text.UTF8Encoding -ArgumentList $false))
Write-Output ('wrote {0} ({1} lines)' -f $out, ($text -split "`r`n").Count)
